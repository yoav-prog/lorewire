def silence_mp3_for(params: dict | None) -> bytes | None:
    """Silence blob matching a clip's `voice.mp3_stream_params`, or None."""
    if not params:
        return None
    key = (
        params.get("version"),
        params.get("layer"),
        params.get("sample_rate"),
        params.get("channels"),
    )
    blob = _SILENCE_B64.get(key)
    return base64.b64decode(blob) if blob else None
